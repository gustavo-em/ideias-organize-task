const { readFileSync, writeFileSync } = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'assets/brand/ideias-wordmark.svg');
const componentsPath = path.join(root, 'src/app/components');
const wordmarkFile = 'AppWordmark.generated.tsx';
const destinationPath = path.join(componentsPath, wordmarkFile);

const source = readFileSync(sourcePath, 'utf8');
const svg = source
  .replace(/^<\?xml[^>]+>\s*/u, '')
  .replace(/ width="[^"]+"/u, '')
  .replace(/ height="[^"]+"/u, '')
  .replace(/fill="rgb\([^"]+\)"/u, 'fill="currentColor"')
  .trim();

if (!svg.includes('viewBox="0 0 2816 758"')) {
  const message =
    'Wordmark SVG inesperado; revise a exportação antes de gerar.';
  throw new Error(message);
}

const output = `// Generated by scripts/generate-wordmark-component.cjs. Do not edit.
import { useMemo } from 'react';
import { SvgXml } from 'react-native-svg';

export const IDEIAS_WORDMARK_LICENSE = 'SIL Open Font License 1.1';
export const IDEIAS_WORDMARK_SOURCE =
  'https://github.com/google/fonts/tree/main/ofl/bricolagegrotesque';
export const IDEIAS_WORDMARK_VIEWBOX = '0 0 2816 758';

const WORDMARK_SVG = ${JSON.stringify(svg)};

interface AppWordmarkProps {
  color: string;
}

export function AppWordmark({ color }: AppWordmarkProps) {
  const xml = useMemo(
    () => WORDMARK_SVG.replace('currentColor', color),
    [color],
  );
  return <SvgXml height={22} width={79} xml={xml} />;
}
`;

writeFileSync(destinationPath, output, 'utf8');
console.log(`Generated ${path.relative(root, destinationPath)}`);
